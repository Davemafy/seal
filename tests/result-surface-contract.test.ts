import {describe,it,expect} from 'vitest';
import {readFileSync} from 'node:fs';

describe('result surface design contract',()=>{
 it('keeps Summary visually anchored while deeper reasoning stays progressive',()=>{
  const app=readFileSync('app/seal-app.tsx','utf8');
  const css=readFileSync('app/workspace.css','utf8');
  const mobileCss=readFileSync('app/result-mobile-repair.css','utf8');
  expect(app).toContain('className="decision-overview"');
  expect(app).toContain('result-slide result-slide-summary');
  expect(app).toContain('result-slide result-slide-original');
  expect(app).toContain('className="decision-visual"');
  expect(app).toContain('className="decision-artifact"');
  expect(app).toContain("aria-label={resultUi('checkSnapshot')}");
  expect(app).toContain('data-testid="play-evidence-review"');
  expect(app).not.toContain('setTimeout(()=>startStory(),260)');
  expect(css).toContain('Visual result composition: focused reading column + contextual artifact.');
  expect(app).toContain("const primaryRoute=file?.sample");
  expect(app).toContain("resultStatusLabel=file?.sample");
  expect(app).toContain("{workspaces.map((item,index)=>{");
  expect(app).not.toContain('<select value={displayLocale}');
  expect(app).toContain("setWorkspaceTransition({from:activeWorkspace,to:id,direction,snapshot:workspaces.map(item=>({...item}))})");
  expect(app).toContain("},[activeWorkspace,workspaces]);");
  expect(app).toContain('data-workspace-id={workspace.id}');
  expect(app).toContain("workspaceTransition?.to===workspace.id");
  expect(app).toContain("workspaceTransition?.from===workspace.id");
  expect(css).toContain('@keyframes workspace-sheet-rise');
  expect(css).toContain('transform:translate3d(0,100dvh,0)');
  expect(css).toContain('@keyframes workspace-page-recede');
  expect(css).toContain('scale(.94)');
  expect(css).toContain('.workspace-drawer-layer.is-open');
  expect(app).not.toContain('finishWorkspaceSwipe');
  expect(app).not.toContain('onTouchStart={beginWorkspaceSwipe}');
  expect(app).toContain('name="workspaces"');
  expect(app).toContain('workspace-page-edges');
  expect(app).not.toContain('mobile-workspace-count');
  expect(app).toContain("workspaces.length>1?'has-multiple':''");
  expect(css).toContain('Persistent multi-workspace resting cue.');
  expect(css).toContain('translate3d(0,100dvh,0)');
  expect(css).toContain('font-size:37px!important');
  expect(app).toContain('data-testid="first-run-onboarding"');
  expect(app).toContain('window.localStorage.getItem(ONBOARDING_KEY)');
  expect(app).toContain('aria-label="Check progress"');
  expect(app).toContain("label:'Read document'");
  expect(app).toContain("label:'Find instructions'");
  expect(app).toContain("label:'Check public sources'");
  expect(css).toContain('never fake percentage progress');
  expect(css).toContain('Result grid repair: shell must occupy the content rows');
  expect(css).toContain('grid-row:1 / 3!important');
  expect(css).toContain('flex:1 1 auto!important');
  expect(mobileCss).toContain('.result-slide-summary .decision-visual{display:none!important}');
  expect(mobileCss).toContain('.result-slide-evidence .evidence-review-entry');
  expect(mobileCss).toContain('Tabs behave as real sibling pages');
 });
});
